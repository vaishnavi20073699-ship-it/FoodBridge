require("dotenv").config({path:require("path").join(__dirname,"../.env")});
const express=require("express");
const cors=require("cors");
const rateLimit=require("express-rate-limit");
const connectDB=require("./config/db");
const authRoutes=require("./routes/auth");
const listingRoutes=require("./routes/listings");
const requestRoutes=require("./routes/requests");
const organizationRoutes=require("./routes/organizations");
const reportRoutes=require("./routes/reports");
const dashboardRoutes=require("./routes/dashboard");
const app=express();
app.use(cors({origin:process.env.CLIENT_ORIGIN||"http://localhost:5173"}));
app.use(express.json({limit:"1mb"}));
app.use("/api/auth",rateLimit({windowMs:15*60*1000,max:100}),authRoutes);
app.use("/api/listings",listingRoutes);
app.use("/api/requests",requestRoutes);
app.use("/api/organizations",organizationRoutes);
app.use("/api/reports",reportRoutes);
app.use("/api/dashboard",dashboardRoutes);
app.get("/api/health",(req,res)=>res.json({ok:true,service:"FoodBridge API"}));
app.use((err,req,res,next)=>{
 console.error(err);
 if(err.name==="ValidationError")return res.status(400).json({error:Object.values(err.errors).map(x=>x.message).join(", ")});
 if(err.name==="CastError")return res.status(400).json({error:"Invalid identifier."});
 if(err.code===11000)return res.status(409).json({error:"A record with that unique value already exists."});
 if(err.status)return res.status(err.status).json({error:err.message});
 if(err.code==="TransientTransactionError"||/transaction numbers are only allowed/i.test(err.message||""))return res.status(503).json({error:"MongoDB transaction unavailable. Check that your Atlas cluster supports transactions."});
 res.status(500).json({error:"Server error. Check the terminal logs."});
});
const port=process.env.PORT||5000;
connectDB().then(()=>app.listen(port,()=>console.log(`FoodBridge API running at http://localhost:${port}`))).catch(e=>{console.error("Database connection failed:",e.message);process.exit(1);});
